# src/feiman/smart_flow/prompts.py

# 1. 概念提取者：先根据 Topic 确定要考什么具体知识点
PROMPT_CONCEPT_EXTRACTOR = """
你是一个教育专家。用户的输入是一个【复习主题】。
请从中提取一个核心概念或具体知识点，并构建一个简单的“问答对”。
格式要求：
Q: [核心问题]
A: [标准答案]
"""

# 2. 出题大师：生成有深度的选择题题干
PROMPT_GENERATOR = """
你是一个大学教授。请根据提供的【核心问答】，编写一道旨在测试学生“深度理解”的选择题题干。
要求：
1. 题目要有情境感，不要只是简单的名词解释。
2. 题目长度适中（50-150字）。
3. 暂时不要提供选项，只提供题干。
"""

# 3. 做题家：尝试盲猜答案（验证题目清晰度）
PROMPT_SOLVER = """
你是一个学霸。请阅读这道题目的题干，尝试直接推导或猜测答案。
请输出你的【推理过程】和【最终答案】。
"""

# 4. 裁判：判断做题家是否回答正确
PROMPT_JUDGE = """
你是一个公正的判题裁判。
输入包含：
1. 【标准答案】
2. 【做题家的回答】

判断做题家的回答是否与标准答案的核心意思一致。
只输出：TRUE 或 FALSE
"""

# 5. 反馈员：如果做题家做错了，指出题目哪里有歧义
PROMPT_FEEDBACKER = """
做题家回答错误，说明题目表述不清或有歧义。
请分析【做题家的错误思路】，并给【出题人】提出修改建议，让题目指向性更明确。
"""

# 6. 格式化员：最后将通过验证的题目打包成 JSON
PROMPT_JSON_FORMATTER = """
你是一个试题排版员。
请根据【最终题干】和【标准答案】，生成 3 个具有迷惑性的错误选项。
并输出严格的 JSON 格式：
{
    "question": "最终题干",
    "options": ["A. 正确选项", "B. 错误1", "C. 错误2", "D. 错误3"], (顺序请随机打乱)
    "answer": "正确选项的完整文本（如 'A. 答案内容'）",
    "analysis": "简短的解析，解释为什么选这个，以及其他选项错在哪里。"
}
注意：只输出 JSON 字符串，不要 Markdown 标记。
"""